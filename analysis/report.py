REGRESSION_OUTCOME_LABELS = {
    "log_unit_spend": "Log spending per unit",
    "log_claim_spend": "Log spending per claim",
    "log_retail_price": "Log retail price",
    "log_markup": "Log markup",
}


def _stars(pvalue: float) -> str:
    if pvalue < 0.01:
        return "^{***}"
    if pvalue < 0.05:
        return "^{**}"
    if pvalue < 0.1:
        return "^{*}"
    return ""


def _coefficient(value: float, pvalue: float) -> str:
    return f"${value:.3f}{_stars(pvalue)}$"


def _number(value: float) -> str:
    """Use readable magnitudes without rounding tiny positive minima to zero."""
    if not np.isfinite(value):
        return "---"
    if value == 0:
        return "0"
    if abs(value) < 0.001:
        return f"{value:.4g}"
    if abs(value) >= 1000:
        return f"{value:,.0f}"
    return f"{value:,.3f}"


def _regression_table(
    models: Sequence[ModelResult],
    caption: str,
    label: str,
    *,
    medicaid: bool,
) -> str:
    columns = len(models)
    outcome_heading = rf"\textbf{{{REGRESSION_OUTCOME_LABELS[models[0].outcome]}}}"
    rows = [
        "% Generated by python -m analysis.run; do not edit.",
        r"\begin{table}[!htbp]",
        r"\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        r"\begin{singlespace}",
        r"\small",
        r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}l"
        + "c" * columns
        + "@{}}",
        r"\toprule",
        r"\textit{Dependent variable:} & "
        + rf"\multicolumn{{{columns}}}{{c}}{{{outcome_heading}}}"
        + r" \\",
        r"\addlinespace[3pt]",
        " & " + " & ".join(f"({i + 1})" for i in range(columns)) + r" \\",
        r"\midrule",
    ]
    terms = (
        [
            ("Tot_Mftr", "Number of manufacturers"),
            ("log_claims", "Log prescription claims"),
            ("const", "Constant"),
        ]
        if medicaid
        else [
            ("log_manuf_cost", "Log estimated manufacturing cost"),
            ("const", "Constant"),
        ]
    )
    for term, title in terms:
        cells = []
        standard_errors = []
        for model in models:
            result = model.result
            if term in result.params.index:
                cells.append(_coefficient(result.params[term], result.pvalues[term]))
                standard_errors.append(f"({result.bse[term]:.3f})")
            else:
                cells.append("")
                standard_errors.append("")
        rows.append(title + " & " + " & ".join(cells) + r" \\")
        rows.append(" & " + " & ".join(standard_errors) + r" \\")
        rows.append(r"\addlinespace[2pt]")
    rows.append(r"\midrule")
    if medicaid:
        rows += [
            "Year fixed effects & " + " & ".join(["Yes"] * columns) + r" \\",
            "Drug fixed effects & " + " & ".join(["No"] * columns) + r" \\",
        ]
    rows += [
        "Observations & "
        + " & ".join(f"{int(model.result.nobs):,}" for model in models)
        + r" \\",
    ]
    if medicaid:
        rows.append(
            "Drug groups & "
            + " & ".join(f"{model.n_groups:,}" for model in models)
            + r" \\"
        )
    rows += [
        r"$R^2$ & "
        + " & ".join(f"{model.result.rsquared:.3f}" for model in models)
        + r" \\",
        r"Adjusted $R^2$ & "
        + " & ".join(f"{model.result.rsquared_adj:.3f}" for model in models)
        + r" \\",
        r"\bottomrule",
        r"\end{tabular*}",
        r"\vspace{4pt}",
        r"\begin{minipage}{\linewidth}",
        r"\footnotesize",
    ]
    if medicaid:
        rows.append(
            r"\textit{Notes:} OLS with year indicators for 2017--2021 "
            r"(2017 omitted). Drug groups are brand-name/generic-name pairs. "
            r"Standard errors in parentheses are clustered by drug group, "
            r"with a finite-sample correction. Tests use a $t$ distribution "
            r"with the number of groups minus one degrees of freedom. "
            r"Manufacturer counts are time-invariant in these data."
        )
        if models[0].outcome == "log_unit_spend":
            rows.append(
                "Per-unit spending is the reported weighted average per dosage unit."
            )
    else:
        note = (
            r"\textit{Notes:} OLS using the saved Cost Plus snapshot. "
            r"HC3 heteroskedasticity-robust standard errors in parentheses; "
            r"tests use the asymptotic normal distribution. "
            r"Estimated manufacturing cost is $(\mathrm{CP\ price}-3)/1.15$."
        )
        if models[0].outcome == "log_markup":
            note += (
                r" The constructed markup is "
                r"$100[(\mathrm{retail\ price}-3)/\mathrm{estimated\ cost}-1]$."
            )
        rows.append(note)
    rows.append("All logarithms are natural.")
    rows += [
        r"$^{*}p<0.10$; $^{**}p<0.05$; $^{***}p<0.01$.",
        r"\end{minipage}",
        r"\end{singlespace}",
        r"\end{table}",
        "",
    ]
    return "\n".join(rows)


def _descriptive_table(
    frame: pd.DataFrame,
    labels: dict[str, str],
    caption: str,
    label: str,
    note: str,
) -> tuple[str, pd.DataFrame]:
    statistics = (
        frame[list(labels)]
        .agg(["count", "mean", "std", "min", "max"])
        .T.rename_axis("variable")
    )
    rows = [
        "% Generated by python -m analysis.run; do not edit.",
        r"\begin{table}[!htbp]",
        r"\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        r"\begin{singlespace}",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabularx}{\linewidth}{@{}Xrrrrr@{}}",
        r"\toprule",
        r"Variable & $N$ & Mean & Std. dev. & Min. & Max. \\",
        r"\midrule",
    ]
    for variable, values in statistics.iterrows():
        cells = [f"{int(values['count']):,}"] + [
            _number(float(values[name])) for name in ["mean", "std", "min", "max"]
        ]
        rows.append(labels[variable] + " & " + " & ".join(cells) + r" \\")
    rows += [
        r"\bottomrule",
        r"\end{tabularx}",
        r"\vspace{4pt}",
        r"\begin{minipage}{\linewidth}",
        r"\footnotesize",
        r"\textit{Notes:} " + note,
        "Statistics use available observations; missing values are not "
        "replaced with zero. Large values are rounded to whole units; "
        "small positive values retain additional precision.",
        r"\end{minipage}",
        r"\end{singlespace}",
        r"\end{table}",
        "",
    ]
    return "\n".join(rows), statistics.reset_index()


def _save_figure(fig: plt.Figure, path: Path) -> None:
    fig.savefig(
        path,
        bbox_inches="tight",
        metadata={"CreationDate": None, "ModDate": None},
    )
    plt.close(fig)


def _figures(
    figures: Path, output_dir: Path, filtered: pd.DataFrame, costplus: pd.DataFrame
) -> None:
    by_manufacturers = (
        filtered.groupby("Tot_Mftr", sort=True)
        .agg(
            mean_spending_per_dosage_unit=("Avg_Spnd_Per_Dsg_Unt_Wghtd", "mean"),
            observations=("Avg_Spnd_Per_Dsg_Unt_Wghtd", "size"),
            drug_groups=("drug_group_id", "nunique"),
        )
        .reset_index()
    )
    by_manufacturers.to_csv(
        output_dir / "mean_spending_by_manufacturers.csv",
        index=False,
        float_format="%.17g",
    )
    with plt.rc_context(
        {
            "font.size": 10,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "figure.dpi": 120,
            "pdf.fonttype": 42,
        }
    ):
        fig, ax = plt.subplots(figsize=(6.4, 4.1), layout="constrained")
        ax.scatter(
            by_manufacturers["Tot_Mftr"],
            by_manufacturers["mean_spending_per_dosage_unit"],
            color="#235789",
            s=32,
        )
        ax.set_xlabel("Number of manufacturers")
        ax.set_ylabel("Mean spending per dosage unit ($)")
        ax.set_xlim(left=0)
        ax.set_ylim(bottom=0)
        ax.grid(axis="y", alpha=0.2)
        _save_figure(fig, figures / "medicaid_mean_spending.pdf")

        fig, ax = plt.subplots(figsize=(6.4, 4.1), layout="constrained")
        ax.scatter(
            costplus["manuf_cost"],
            costplus["retail_price"],
            color="#235789",
            s=18,
            alpha=0.6,
            linewidths=0,
        )
        ax.set_xlabel("Estimated manufacturing cost ($)")
        ax.set_ylabel("Reported retail price ($)")
        ax.grid(alpha=0.15)
        _save_figure(fig, figures / "costplus_levels.pdf")

        fig, axes = plt.subplots(
            ncols=2, figsize=(9.0, 3.8), layout="constrained"
        )
        for ax, outcome, ylabel in zip(
            axes,
            ["log_retail_price", "log_markup"],
            ["Log reported retail price", "Log constructed markup"],
        ):
            ax.scatter(
                costplus["log_manuf_cost"],
                costplus[outcome],
                color="#235789",
                s=17,
                alpha=0.6,
                linewidths=0,
            )
            ax.set_xlabel("Log estimated manufacturing cost")
            ax.set_ylabel(ylabel)
            ax.grid(alpha=0.15)
        _save_figure(fig, figures / "costplus_logs.pdf")

        # Retain the historical two-panel figure above; the revised manuscript
        # presents only the retail-price relationship.
        fig, ax = plt.subplots(figsize=(6.4, 4.1), layout="constrained")
        ax.scatter(
            costplus["log_manuf_cost"],
            costplus["log_retail_price"],
            color="#235789",
            s=17,
            alpha=0.6,
            linewidths=0,
        )
        ax.set_xlabel("Log estimated manufacturing cost")
        ax.set_ylabel("Log reported retail price")
        ax.grid(alpha=0.15)
        _save_figure(fig, figures / "costplus_retail_log.pdf")


def write_reports(
    output_dir: Path,
    panel: pd.DataFrame,
    filtered: pd.DataFrame,
    costplus: pd.DataFrame,
    medicaid: Sequence[ModelResult],
    cp: Sequence[ModelResult],
) -> None:
    """Write generated tables, descriptive CSVs, and reproducible figures."""
    tables = output_dir / "tables"
    figures = output_dir / "figures"
    tables.mkdir(parents=True, exist_ok=True)
    figures.mkdir(parents=True, exist_ok=True)
    for outcome, filename, caption, label in [
        (
            "log_unit_spend",
            "medicaid_unit.tex",
            "Manufacturer counts and log spending per dosage unit",
            "table:table1",
        ),
        (
            "log_claim_spend",
            "medicaid_claim.tex",
            "Manufacturer counts and log spending per prescription claim",
            "table:table3",
        ),
    ]:
        models = [model for model in medicaid if model.outcome == outcome]
        models.sort(key=lambda model: model.with_claims)
        if len(models) != 2:
            raise ValueError(f"Expected two specifications for {outcome}.")
        (tables / filename).write_text(
            _regression_table(models, caption, label, medicaid=True)
        )
    for outcome, filename, caption, label in [
        (
            "log_retail_price",
            "costplus_retail.tex",
            "Estimated manufacturing cost and log reported retail price",
            "table:costplus-retail",
        ),
        (
            "log_markup",
            "costplus_markup.tex",
            "Estimated manufacturing cost and log constructed markup",
            "table:costplus-markup",
        ),
    ]:
        models = [model for model in cp if model.outcome == outcome]
        if len(models) != 1:
            raise ValueError(f"Expected one Cost Plus model for {outcome}.")
        (tables / filename).write_text(
            _regression_table(models, caption, label, medicaid=False)
        )
    for frame, labels, filename, caption, label, note in [
        (
            panel,
            MEDICAID_LABELS,
            "medicaid_all",
            "Summary statistics: Medicaid, unfiltered",
            "summary:medicaid-all",
            "All manufacturer-specific and Overall records, 2017--2021. "
            "Records for different manufacturers are not independent market totals.",
        ),
        (
            filtered,
            MEDICAID_LABELS,
            "medicaid_filtered",
            "Summary statistics: Medicaid analysis sample",
            "summary:medicaid-filtered",
            "Overall records with no outlier flag and positive observed spending, "
            "dosage units, claims, both spending averages, and manufacturer count.",
        ),
        (
            costplus,
            COSTPLUS_LABELS,
            "costplus_summary",
            "Summary statistics: Cost Plus",
            "summary:costplus",
            "Saved historical snapshot. Estimated manufacturing cost and markup "
            "are constructed from reported prices.",
        ),
    ]:
        text, statistics = _descriptive_table(
            frame, labels, caption, label, note
        )
        (tables / f"{filename}.tex").write_text(text)
        statistics.to_csv(
            output_dir / f"{filename}_summary.csv",
            index=False,
            float_format="%.17g",
        )
    _figures(figures, output_dir, filtered, costplus)
